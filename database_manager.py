def guardar_documento(nombre_archivo, tipo_seguro, texto_extraido, datos_claude):
    conexion = conectar()
    cursor = conexion.cursor()

    id_var = cursor.var(int)
    sql = """
          INSERT INTO documentos (nombre_archivo, tipo_seguro, texto_extraido, json_claude, fecha_importacion)
          VALUES (:1, :2, :3, :4, :5)
              RETURNING id INTO :6 \
          """

    cursor.execute(sql, (
        nombre_archivo,
        tipo_seguro,
        texto_extraido,
        json.dumps(datos_claude, ensure_ascii=False),
        datetime.now(),
        id_var
    ))

    id_doc = id_var.getvalue()[0]
    conexion.commit()
    cursor.close()
    conexion.close()
    return id_doc

