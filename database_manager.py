import os
import re
import json
import unicodedata
import oracledb
from datetime import datetime
from dotenv import load_dotenv

load_dotenv()

# ─────────────────────────────────────────────
# CONFIGURACIÓN ORACLE
# ─────────────────────────────────────────────
ORACLE_USER = os.getenv("ORACLE_USER")
ORACLE_PASSWORD = os.getenv("ORACLE_PASSWORD")
ORACLE_DSN = os.getenv("ORACLE_DSN") # Ejemplo: localhost:1521/xe

def conectar():
    return oracledb.connect(
        user=ORACLE_USER,
        password=ORACLE_PASSWORD,
        dsn=ORACLE_DSN
    )

def proteger_nombre_oracle(nombre):
    """Encapsula nombres en comillas dobles y mayúsculas para Oracle."""
    return f'"{nombre.upper()}"'

# ─────────────────────────────────────────────
# INICIALIZACIÓN
# ─────────────────────────────────────────────

def inicializar_bbdd():
    conexion = conectar()
    cursor = conexion.cursor()

    # Tablas base del sistema
    tablas = {
        "DOCUMENTOS": """
                      CREATE TABLE documentos (
                                                  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  nombre_archivo VARCHAR2(255),
                                                  tipo_seguro VARCHAR2(100),
                                                  texto_extraido CLOB,
                                                  json_claude CLOB,
                                                  fecha_importacion TIMESTAMP
                      )""",
        "TABLAS_GENERADAS": """
                            CREATE TABLE tablas_generadas (
                                                              id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                              id_documento NUMBER,
                                                              nombre_logico VARCHAR2(150),
                                                              nombre_oracle VARCHAR2(150),
                                                              filas_insertadas NUMBER,
                                                              fecha_creacion TIMESTAMP,
                                                              CONSTRAINT fk_doc FOREIGN KEY (id_documento) REFERENCES documentos(id) ON DELETE CASCADE
                            )""",
        "ERRORES_IMPORTACION": """
                               CREATE TABLE errores_importacion (
                                                                    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                                    id_documento NUMBER NULL,
                                                                    mensaje_error CLOB,
                                                                    fecha TIMESTAMP
                               )"""
    }

    for nombre, ddl in tablas.items():
        try:
            cursor.execute(ddl)
        except oracledb.DatabaseError as e:
            error, = e.args
            if error.code != 955: # ORA-00955: ya existe el nombre
                raise

    conexion.commit()
    cursor.close()
    conexion.close()

